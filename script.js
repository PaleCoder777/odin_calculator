// Basic Math Operators Functions
function mathAdd(num1, num2) {
    return (num1 + num2);
}

function mathSubtract(num1, num2) {
    return (num1 - num2);
}

function mathMultiply(num1, num2) {
    return (num1 * num2);
}

function mathDivide(num1, num2) {
    return (num1 / num2);
}